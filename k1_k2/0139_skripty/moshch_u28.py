# к1 0139: мощность правила «оба 99 %» (t₉ определяет, к1 0135) для новой пробы U28 (б) при n = 10 исполнителях.
# Разброс разностей по исполнителям — из прошлой строки U28: SE = (2,39 − (−0,29)) / 2 / 3,250 = 0,412 → s = SE·√10.
import numpy as np
from scipy import stats
n = 10; tq = stats.t.ppf(0.995, n - 1)
se = (2.39 + 0.29) / 2 / tq; s = se * np.sqrt(n)
print(f"t₉(0,995; 9) = {tq:.3f}; SE = {se:.3f}; s по исполнителям = {s:.3f}")
for mu in (0.5, 0.75, 1.05, 1.5, 2.0):
    pw = 1 - stats.nct.cdf(tq, n - 1, mu / se)
    print(f"истинный эффект {mu:4.2f} п. п.: P(«установлено») = {pw:.3f}")
# с учётом неопределённости самого эффекта: μ ~ N(1,05; SE²) (прошлая оценка как априорное)
rng = np.random.default_rng(139); mus = rng.normal(1.05, se, 200_000)
print(f"с неопределённостью μ ~ N(1,05; {se:.3f}²): P(«установлено») = {np.mean(1 - stats.nct.cdf(tq, n - 1, mus / se)):.3f}")
