"""к3 0048: в. 2 / Б1 — доля исходов, где окно 12 ч после UzSohn_M13.done почти не пересекается с рабочими часами 9:00–21:00.
Допущения (все — входы, не измерения): g1.done ~ U(20.11 16:00; 21.11 00:00) (к2: «≈ 20.11 вечер»); +3 мин; окно (а) U01b ~ U(6; 8) ч
(к2 0155: «≈ 7 ч»), или пропущено; M13 ~ U(47; 53) ч (П26, моя арифметика 0042). Без Б1 в окне нужно: слияние у к2 + сверка хеша к1 и к3."""
import numpy as np
rng = np.random.default_rng(20261117); N = 1_000_000
def overlap(t0):   # часы пересечения [t0, t0+12) с [9, 21) каждого дня; t0 — часы от 20.11 00:00
    s = 0.0
    for d in range(0, 7):
        a, b = 24 * d + 9, 24 * d + 21
        s = s + np.clip(np.minimum(t0 + 12, b) - np.maximum(t0, a), 0, None)
    return s
for name, u01b in (("с окном (а) U01b", rng.uniform(6, 8, N)), ("окно (а) пропущено", np.zeros(N))):
    end = rng.uniform(16, 24, N) + 0.05 + u01b + rng.uniform(47, 53, N)
    ov = overlap(end); tod = end % 24
    print(f"{name}: конец M13 — {np.percentile(tod, 5):4.1f}…{np.percentile(tod, 95):4.1f} ч (5–95 %, по модулю суток); "
          f"рабочих часов в окне 12 ч: < 3 ч — {np.mean(ov < 3):.2f}, < 6 ч — {np.mean(ov < 6):.2f}, 0 ч — {np.mean(ov == 0):.2f}")
