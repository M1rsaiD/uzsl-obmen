"""к3 0041: счёт к голосу по В1–В2 (0156). ЦП, только числа из писем; данных нет."""
import numpy as np
from scipy import stats

# В2. Мощность повтора U28 при том же SE (к3 0039 разд. 7: центр 1,05; SE 0,412; t9 0,995 = 3,2498)
d, se, df = 1.05, 0.412, 9
tc = stats.t.ppf(0.995, df)
assert abs(tc - 3.2498) < 1e-3 and abs((2.39 - (-0.29)) / 2 / tc - se) < 2e-3  # SE из t9-интервала П25
p_norm = stats.norm.sf((tc * se - d) / se)            # SE известен
p_nct = stats.nct.sf(tc, df, d / se)                  # SE оценивается по 10 фолдам
print(f"В2: t_crit {tc:.4f}; P(нижняя граница t9 > 0 | δ = 1,05): {p_norm:.3f} (SE известен), {p_nct:.3f} (нецентр. t)")
for dd in (0.5, 1.05, 2.05):
    print(f"   δ = {dd:4.2f}: {stats.nct.sf(tc, df, dd / se):.3f}")

# В1. Накопленный риск ложного принятия 1 − (1 − α1)^n по α1 модели 3.5 (к3 0040: 0,054–0,108) — только порядок
for n in (5, 8, 13):
    lo, hi = (1 - (1 - a) ** n for a in (0.054, 0.108))
    print(f"В1: n = {n:2d}: {lo:.3f}–{hi:.3f}")

