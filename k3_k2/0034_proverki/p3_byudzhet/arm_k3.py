"""к3: проверка «отбор одного плеча ≈ 6,4 ч по часам» и сумм разд. 7 своим кодом (модель: 3 места, старт с шагом 180 с,
следующий прогон — на первое освободившееся место, 1,677 с/шаг на процесс; шаги фолдов — разд. 2)."""
import heapq
steps = [4200, 3900, 3000, 2700, 3600, 4200, 3600, 3600, 4200, 4200]   # S11 … S09, разд. 2
sps = 56.62 * 3600 / 121500
print(f"с/шаг = {sps:.4f}; отбор, процесс-ч = {sum(steps) * sps / 3600:.2f}")
def makespan(order, J=3, gap=180):
    free = [0.0] * J; heapq.heapify(free); t_last = -gap; end = 0
    for s in order:
        t = max(heapq.heappop(free), t_last + gap); t_last = t
        e = t + s * sps; end = max(end, e); heapq.heappush(free, e)
    return end / 3600
print(f"по часам (порядок разд. 2) = {makespan(steps):.2f} ч; по убыванию = {makespan(sorted(steps, reverse=True)):.2f} ч; нижняя граница = {sum(steps)*sps/3600/3:.2f} ч")
