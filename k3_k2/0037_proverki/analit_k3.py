"""к3 0037: аналитическая сверка максимумов — доля ≈ (1 − p)¹⁰ · P(t₉ > 3,25 | нецентр. δ = √10 · выигрыш / s)
(вклад наборов, где есть исполнитель другого типа, пренебрежимо мал: t ≈ 1)."""
import numpy as np
from scipy import stats
from max_pri_asimm_k3 import s_for
T9 = stats.t.ppf(0.995, 9)
for gam, p in ((-1.4, 0.189), (-1.41, 0.188), (-1.58, 0.170), (-0.7, 0.29)):
    s = s_for(p, gam); b = p / (1 - p)
    v = (1 - p) ** 10 * stats.nct.sf(T9, 9, np.sqrt(10) * b / s)
    print(f"γ = {gam}, p = {p}: s/выигрыш = {s/b:.2f}; (1 − p)¹⁰ = {100*(1-p)**10:.2f} %; аналитика {100*v:.2f} %")
